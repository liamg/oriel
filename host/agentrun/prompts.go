// promptsPath is where the host keeps the prompts the app last sent, for sessions that start while no app is
// connected.
func (x *Runner) promptsPath() string { return filepath.Join(x.env.Home, "prompts.json") }

func (x *Runner) loadPrompts() {
	b, err := os.ReadFile(x.promptsPath())
	if errors.Is(err, fs.ErrNotExist) {
		return
	}
	var o prompts.Overrides
	if err == nil {
		err = json.Unmarshal(b, &o)
	}
	if err != nil {
		x.env.Log.Warn("prompts", "path", x.promptsPath(), "err", err)
		return
	}
	x.mu.Lock()
	x.prompts, x.promptsSent = o, true
	x.mu.Unlock()
}

// SetPrompts is the user's versions of the prompts (agent/prompts), sent by the app on connect and whenever one
// changes. They're the source of truth from then on: a built-in pack is theirs or the default, never an older
// file's. Each workspace's notes are written again with the coding style.
func (x *Runner) SetPrompts(o prompts.Overrides) error {
	if o == nil {
		o = prompts.Overrides{}
	}
	b, err := json.MarshalIndent(o, "", "  ")
	if err != nil {
		return err
	}
	if err := atomicfile.Write(x.promptsPath(), append(b, '\n'), 0o600); err != nil {
		return err
	}
	x.mu.Lock()
	x.prompts, x.promptsSent = o, true
	x.mu.Unlock()
	for _, se := range x.st.Snapshot().Sessions {
		if !se.Archived {
			x.WriteNotes(se.ID)
		}
	}
	return nil
}

// Prompts is the user's versions of the prompts the app last sent, and whether it has.
func (x *Runner) Prompts() (prompts.Overrides, bool) {
	x.mu.Lock()
	defer x.mu.Unlock()
	return x.prompts, x.promptsSent
}

// Pack is a session kind's prompt pack: with the user's versions in once the app has sent them, else as Packs has it.
func (x *Runner) Pack(name string) (agent.Pack, bool) {
	o, sent := x.Prompts()
	if !sent {
		if x.deps.Packs == nil {
			return agent.Pack{}, false
		}
		return x.deps.Packs(name)
	}
	return o.Pack(name, x.deps.Packs)
}

// WriteNotes writes the agent notes at a workspace's root (crit's WriteAgentNotes): the projects and where their
// own instructions are, since an agent reads CLAUDE.md from its cwd upward and never sees theirs below it; and
// the coding style, so it applies however the agent got there. Only workspaces Oriel made have them.
func (x *Runner) WriteNotes(id core.SessionID) {
	se, err := x.st.Session(id)
	if err != nil || se.Dir == "" {
		return
	}
	if rel, err := filepath.Rel(x.env.WorkspacesDir(), se.Dir); err != nil || rel == "." || strings.HasPrefix(rel, "..") {
		return
	}
	if _, err := os.Stat(se.Dir); err != nil {
		return
	}
	o, _ := x.Prompts()
	k := x.deps.Kinds.Spec(se)
	text := agentNotes(se, o.Style(), k.Can(core.OwnsBranch) && k.Can(core.Ships))
	files := x.notesFiles()
	if gitDir := filepath.Join(se.Dir, ".git"); isDir(gitDir) {
		if err := excludeIn(gitDir, files...); err != nil {
			x.env.Log.Warn("agent notes", "session", id, "err", err)
		}
	}
	for _, name := range files {
		if err := writeIfChanged(filepath.Join(se.Dir, name), text); err != nil {
			x.env.Log.Warn("agent notes", "session", id, "err", err)
		}
	}
}

// notesFiles are the files the notes go in (agent.NotesFiles).
func (x *Runner) notesFiles() []string {
	if x.deps.Providers == nil {
		return agent.NotesFiles(nil)
	}
	return agent.NotesFiles(x.deps.Providers.List())
}

// agentNotes are a workspace's notes; with branches, each project's branch, and how to change it.
func agentNotes(se core.SessionState, style string, branches bool) string {
	var b strings.Builder
	b.WriteString("<!-- generated by Oriel; edits are overwritten -->\n")
	b.WriteString("# Workspace: " + cmp.Or(se.Name, string(se.ID)) + "\n\n")
	if len(se.Projects) == 0 {
		b.WriteString("No projects yet.\n")
	} else {
		b.WriteString("Projects in this workspace. Edit inside a project's directory, not its\n")
		b.WriteString("original checkout, and read its instructions before you change it.\n\n")
		for _, p := range se.Projects {
			dir := p.Dir
			if rel, err := filepath.Rel(se.Dir, p.Dir); err == nil && !strings.HasPrefix(rel, "..") {
				dir = rel
			}
			b.WriteString("- `" + dir + "`")
			if p.Repo != "" && p.Repo != p.Dir {
				b.WriteString(" — " + p.Repo)
			}
			if p.ReadOnly {
				b.WriteString(" — read only")
			}
			for _, name := range []string{"CLAUDE.md", "AGENTS.md"} {
				if _, err := os.Stat(filepath.Join(p.Dir, name)); err == nil {
					b.WriteString(" — see `" + filepath.Join(dir, name) + "`")
					break
				}
			}
			if branches && !p.ReadOnly && p.Branch != "" && !p.Detached {
				b.WriteString(" — on branch `" + p.Branch + "`")
			}
			b.WriteString("\n")
		}
	}
	if branches && len(se.Projects) > 0 {
		b.WriteString(branchNotes)
	}
	if mem := hostcore.Memories(se); len(mem) > 1 {
		b.WriteString("\n## Memory\n\n")
		for _, m := range mem {
			b.WriteString("- A memory about " + m.Name + " goes in `" + m.Dir + "`.\n")
		}
		b.WriteString("- Anything else goes in your own memory directory.\n\n")
		b.WriteString("Read each of these memory indexes before you start:\n\n")
		for _, m := range mem[1:] {
			b.WriteString("- `" + filepath.Join(m.Dir, "MEMORY.md") + "`\n")
		}
	}
	if style != "" {
		b.WriteString("\n## Coding style\n\n" + style + "\n")
	}
	return b.String()
}

// branchNotes say how a project's branch changes: Oriel pushes and raises PRs only from the one it has recorded.
const branchNotes = "\n## Branches\n\n" +
	"Each project is on this session's branch for it, named above: Oriel pushes and raises pull requests from that branch only.\n" +
	"Don't create, switch or rename branches with git (`git checkout -b`, `git switch`, `git branch -m`): Oriel wouldn't push the result.\n" +
	"To start a fresh branch off the default branch, use `mcp__oriel__new_branch`; to rename this one, `mcp__oriel__rename_branch`.\n"

// excludeIn adds lines to a git dir's info/exclude that aren't there yet: generated files stay out of the plan diff.
func excludeIn(gitDir string, lines ...string) error {
	p := filepath.Join(gitDir, "info", "exclude")
	b, err := os.ReadFile(p)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	have := strings.Split(string(b), "\n")
	out := string(b)
	for _, l := range lines {
		if slices.ContainsFunc(have, func(h string) bool { return strings.TrimSpace(h) == l }) {
			continue
		}
		if out != "" && !strings.HasSuffix(out, "\n") {
			out += "\n"
		}
		out += l + "\n"
	}
	if out == string(b) {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	return os.WriteFile(p, []byte(out), 0o644)
}

func writeIfChanged(path, text string) error {
	if b, err := os.ReadFile(path); err == nil && string(b) == text {
		return nil
	}
	return os.WriteFile(path, []byte(text), 0o644)
}

func isDir(p string) bool {
	fi, err := os.Stat(p)
	return err == nil && fi.IsDir()
}
