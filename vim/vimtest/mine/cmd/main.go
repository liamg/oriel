// Command mine converts vim's tests in spec/vim/testdir into vim/testdata/mined/*.vt.
//
//	cd vim && go run ./vimtest/mine/cmd [-v]
package main

import (
	"cmp"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"sync"

	"github.com/liamg/oriel/vim/vimtest"
	"github.com/liamg/oriel/vim/vimtest/mine"
	"github.com/liamg/oriel/vim/vimtest/nvim"
)

var files = []string{"test_normal", "test_visual", "test_textobjects", "test_undo", "test_put", "test_registers", "test_marks", "test_jumplist", "test_join", "test_increment"}

func main() {
	verbose := flag.Bool("v", false, "list every drop")
	jobs := flag.Int("j", 8, "functions mined in parallel")
	flag.Parse()
	root, err := vimtest.RepoRoot()
	if err != nil {
		fatal(err)
	}
	out := filepath.Join(root, "vim", "testdata", "mined")
	if err := os.MkdirAll(out, 0o755); err != nil {
		fatal(err)
	}
	var total mine.Result
	for _, name := range files {
		src, err := os.ReadFile(filepath.Join(root, "spec", "vim", "testdir", name+".vim"))
		if err != nil {
			fatal(err)
		}
		res := mineFile(name+".vim", string(src), *jobs)
		header := fmt.Sprintf("# Code generated by vim/vimtest/mine from spec/vim/testdir/%s.vim; DO NOT EDIT.\n"+
			"# Regenerate: cd vim && go run ./vimtest/mine/cmd\n"+
			"# Expectations are vim's asserts; a \"from oracle\" note marks a value vim didn't assert, taken from nvim %s.\n",
			name, nvim.Version)
		if err := os.WriteFile(filepath.Join(out, name+".vt"), []byte(mine.Render(header, res.Cases)), 0o644); err != nil {
			fatal(err)
		}
		fmt.Printf("%-18s %4d funcs %5d asserts %5d converted %4d cases\n", name, res.Funcs, res.Asserts, res.Converted, len(res.Cases))
		total.Funcs += res.Funcs
		total.Asserts += res.Asserts
		total.Converted += res.Converted
		total.Cases = append(total.Cases, res.Cases...)
		total.Drops = append(total.Drops, res.Drops...)
	}
	fmt.Printf("%-18s %4d funcs %5d asserts %5d converted %4d cases\n\n", "total", total.Funcs, total.Asserts, total.Converted, len(total.Cases))
	report(total.Drops, *verbose)
}

func mineFile(name, src string, jobs int) mine.Result {
	funcs := mine.Funcs(src)
	helpers := mine.Helpers(src)
	results := make([]mine.Result, len(funcs))
	var wg sync.WaitGroup
	sem := make(chan struct{}, jobs)
	for i, f := range funcs {
		wg.Add(1)
		sem <- struct{}{}
		go func() {
			defer func() { <-sem; wg.Done() }()
			results[i] = mine.MineFunc(name, f, helpers, newSim, oracle)
		}()
	}
	wg.Wait()
	var res mine.Result
	for _, r := range results {
		res.Funcs += r.Funcs
		res.Asserts += r.Asserts
		res.Converted += r.Converted
		res.Cases = append(res.Cases, r.Cases...)
		res.Drops = append(res.Drops, r.Drops...)
	}
	return res
}

type sim struct {
	*nvim.Session
	dir string
}

func newSim() (mine.Sim, error) {
	dir, err := os.MkdirTemp("", "oriel-mine-")
	if err != nil {
		return nil, err
	}
	s, err := nvim.Start(dir)
	if err != nil {
		os.RemoveAll(dir)
		return nil, err
	}
	return &sim{s, dir}, nil
}

func (s *sim) Close() error {
	s.Session.Close()
	return os.RemoveAll(s.dir)
}

func oracle(c vimtest.Case) (vimtest.Result, error) {
	e, err := nvim.New()()
	if err != nil {
		return vimtest.Result{}, err
	}
	defer e.Close()
	if err := e.Load(c.Given); err != nil {
		return vimtest.Result{}, err
	}
	if err := e.Feed(c.Keys); err != nil {
		return vimtest.Result{}, err
	}
	var q vimtest.Query
	for r := range c.Regs {
		q.Regs = append(q.Regs, r)
	}
	for r := range c.Marks {
		q.Marks = append(q.Marks, r)
	}
	slices.Sort(q.Regs)
	slices.Sort(q.Marks)
	return e.Snapshot(q)
}

func report(drops []mine.Drop, verbose bool) {
	type cat struct {
		name           string
		asserts, cases int
		details        []string
	}
	cats := map[string]*cat{}
	for _, d := range drops {
		c := cats[d.Category]
		if c == nil {
			c = &cat{name: d.Category}
			cats[d.Category] = c
		}
		c.asserts += d.Asserts
		c.cases++
		if d.Detail != "" {
			c.details = append(c.details, d.Func+": "+d.Detail)
		}
	}
	var list []*cat
	for _, c := range cats {
		list = append(list, c)
	}
	slices.SortFunc(list, func(a, b *cat) int { return cmp.Compare(b.asserts, a.asserts) })
	fmt.Println("dropped asserts by reason:")
	for _, c := range list {
		fmt.Printf("  %5d  %s\n", c.asserts, c.name)
		if verbose {
			for _, d := range c.details {
				fmt.Printf("           %s\n", strings.ReplaceAll(d, "\n", " "))
			}
		}
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "mine:", err)
	os.Exit(1)
}
