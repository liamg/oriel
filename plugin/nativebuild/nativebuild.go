// Package nativebuild is `oriel build --with`: a custom oriel binary with native plugins (Go packages whose init
// calls plugin.Register) linked in, the way xcaddy builds Caddy.
package nativebuild

import (
	"bufio"
	"bytes"
	"context"
	"errors"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

// Main is the package whose Main runs oriel.
const Main = "github.com/liamg/oriel/cmd/oriel/cli"

// Module is a package to link in, from a version or a local directory: "github.com/x/y@v1.2", "github.com/x/y=../y".
type Module struct {
	Path    string // the import path
	Version string // a version or query for go get; "" for latest, or with Dir
	Dir     string // a local checkout, replacing the module
}

// ParseWith reads a --with: path[@version][=dir].
func ParseWith(s string) (Module, error) {
	var m Module
	s, m.Dir, _ = strings.Cut(s, "=")
	m.Path, m.Version, _ = strings.Cut(s, "@")
	if m.Path == "" || strings.ContainsAny(m.Path, " \t") {
		return m, fmt.Errorf("--with %q isn't a package path[@version][=dir]", s)
	}
	if m.Dir != "" {
		abs, err := filepath.Abs(ExpandHome(m.Dir))
		if err != nil {
			return m, err
		}
		m.Dir = abs
	}
	return m, nil
}

// ExpandHome is a path with ~ as the home directory.
func ExpandHome(p string) string {
	if p == "~" || strings.HasPrefix(p, "~/") {
		if home, err := os.UserHomeDir(); err == nil {
			return filepath.Join(home, p[1:])
		}
	}
	return p
}

// Spec is a build.
type Spec struct {
	Main    string   // the package with Main(); nativebuild.Main if ""
	Base    Module   // the module holding Main: oriel at a version, or a local checkout (its go.work's modules all used)
	With    []Module // the native plugins
	Output  string   // the binary to write
	Tags    []string // build tags
	Env     []string // added to go's environment
	Go      string   // the go command; "go" if ""
	Version string   // the go directive of the generated go.mod; "1.26.0" if ""
	Helper  []byte   // the gzipped sandbox helper the build carries (package helper); none if nil
}

// Plan is a build's generated module: go.mod, main.go, and the go get to run before building.
type Plan struct {
	GoMod, MainGo []byte
	HelperGo      []byte   // carries Spec.Helper, embedded from HelperFile; nil without one
	Get           []string // path@version for each module not from a directory
}

// HelperFile is the gzipped sandbox helper in a build's generated module.
const HelperFile = "oriel-sandbox.gz"

// Make plans a build. Local directories are replaced in go.mod; a local base's go.work brings every module it uses.
func Make(s Spec) (Plan, error) {
	mainPkg := s.Main
	if mainPkg == "" {
		mainPkg = Main
	}
	var p Plan
	replace := map[string]string{} // module path → dir
	if s.Base.Dir != "" {
		mods, err := workModules(s.Base.Dir)
		if err != nil {
			return p, err
		}
		for path, dir := range mods {
			replace[path] = dir
		}
	} else {
		p.Get = append(p.Get, s.Base.Path+"@"+orLatest(s.Base.Version))
	}
	for _, w := range s.With {
		if w.Dir == "" {
			p.Get = append(p.Get, w.Path+"@"+orLatest(w.Version))
			continue
		}
		mod, err := modulePath(w.Dir)
		if err != nil {
			return p, err
		}
		replace[mod] = w.Dir
	}
	var mod bytes.Buffer
	fmt.Fprintf(&mod, "// Generated by oriel build.\nmodule oriel-custom\n\ngo %s\n", orDefault(s.Version, "1.26.0"))
	paths := sortedKeys(replace)
	if len(paths) > 0 {
		mod.WriteString("\nrequire (\n")
		for _, path := range paths {
			fmt.Fprintf(&mod, "\t%s v0.0.0\n", path)
		}
		mod.WriteString(")\n\nreplace (\n")
		for _, path := range paths {
			fmt.Fprintf(&mod, "\t%s => %s\n", path, replace[path])
		}
		mod.WriteString(")\n")
	}
	p.GoMod = mod.Bytes()
	var src bytes.Buffer
	fmt.Fprintf(&src, "// Code generated by oriel build; DO NOT EDIT.\n\npackage main\n\nimport (\n\toriel %q\n\n", mainPkg)
	for _, w := range s.With {
		fmt.Fprintf(&src, "\t_ %q\n", w.Path)
	}
	src.WriteString(")\n\nfunc main() { oriel.Main() }\n")
	p.MainGo = src.Bytes()
	if s.Helper != nil {
		p.HelperGo = fmt.Appendf(nil, "// Code generated by oriel build; DO NOT EDIT.\n\npackage main\n\nimport (\n\t_ \"embed\"\n\n"+
			"\t\"github.com/liamg/oriel/sandbox/helper\"\n)\n\n//go:embed %s\nvar sandboxHelper []byte\n\n"+
			"func init() { helper.Use(sandboxHelper) }\n", HelperFile)
	}
	return p, nil
}

// Build plans and runs a build in a temporary module, writing s.Output.
func Build(ctx context.Context, s Spec, log io.Writer) error {
	if s.Output == "" {
		return errors.New("no output")
	}
	out, err := filepath.Abs(s.Output)
	if err != nil {
		return err
	}
	p, err := Make(s)
	if err != nil {
		return err
	}
	dir, err := os.MkdirTemp("", "oriel-build-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(dir)
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), p.GoMod, 0o644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, "main.go"), p.MainGo, 0o644); err != nil {
		return err
	}
	if p.HelperGo != nil {
		if err := os.WriteFile(filepath.Join(dir, HelperFile), s.Helper, 0o644); err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(dir, "helper.go"), p.HelperGo, 0o644); err != nil {
			return err
		}
	}
	goCmd := orDefault(s.Go, "go")
	run := func(args ...string) error {
		cmd := exec.CommandContext(ctx, goCmd, args...)
		cmd.Dir = dir
		cmd.Env = append(append(os.Environ(), "GOWORK=off", "GOFLAGS=-mod=mod"), s.Env...)
		cmd.Stdout, cmd.Stderr = log, log
		fmt.Fprintln(log, "go", strings.Join(args, " "))
		if err := cmd.Run(); err != nil {
			return fmt.Errorf("go %s: %w", args[0], err)
		}
		return nil
	}
	for _, g := range p.Get {
		if err := run("get", g); err != nil {
			return err
		}
	}
	if err := run("mod", "tidy"); err != nil {
		return err
	}
	args := []string{"build", "-trimpath", "-o", out}
	if len(s.Tags) > 0 {
		args = append(args, "-tags", strings.Join(s.Tags, ","))
	}
	return run(append(args, ".")...)
}

// workModules are the modules a checkout's go.work uses, by path, at their directories; a checkout without one is
// its own module.
func workModules(root string) (map[string]string, error) {
	root, err := filepath.Abs(ExpandHome(root))
	if err != nil {
		return nil, err
	}
	b, err := os.ReadFile(filepath.Join(root, "go.work"))
	if os.IsNotExist(err) {
		mod, err := modulePath(root)
		return map[string]string{mod: root}, err
	}
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	inUse := false
	sc := bufio.NewScanner(bytes.NewReader(b))
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if i := strings.Index(line, "//"); i >= 0 {
			line = strings.TrimSpace(line[:i])
		}
		var dir string
		switch {
		case line == "use (":
			inUse = true
			continue
		case inUse && line == ")":
			inUse = false
			continue
		case inUse && line != "":
			dir = line
		case strings.HasPrefix(line, "use "):
			dir = strings.TrimSpace(strings.TrimPrefix(line, "use"))
		default:
			continue
		}
		dir = filepath.Join(root, strings.Trim(dir, `"`))
		mod, err := modulePath(dir)
		if err != nil {
			return nil, err
		}
		out[mod] = dir
	}
	return out, sc.Err()
}

// modulePath is the module dir/go.mod declares.
func modulePath(dir string) (string, error) {
	b, err := os.ReadFile(filepath.Join(dir, "go.mod"))
	if err != nil {
		return "", err
	}
	for _, line := range strings.Split(string(b), "\n") {
		if rest, ok := strings.CutPrefix(strings.TrimSpace(line), "module "); ok {
			return strings.Trim(strings.TrimSpace(rest), `"`), nil
		}
	}
	return "", fmt.Errorf("%s/go.mod names no module", dir)
}

func orLatest(v string) string { return orDefault(v, "latest") }

func orDefault(v, d string) string {
	if v == "" {
		return d
	}
	return v
}

func sortedKeys(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
