// SignsScene is f.txt committed by you with 30 lines, then in the work tree line 3 changed, two lines added after
// line 10 and line 20 deleted, open in the editor; blame's clock is three days after the commit.
func SignsScene(t *testing.T) (*Scene, *gittest.Repo) {
	r := gittest.New(t)
	r.Git("config", "user.email", "ada@example.com")
	r.Write(map[string]string{"f.txt": gittest.Lines(30)})
	r.Commit("Ada", "thirty lines")
	work := strings.Replace(gittest.Lines(30), "line 3\n", "three\n", 1)
	work = strings.Replace(work, "line 10\n", "line 10\nnew a\nnew b\n", 1)
	work = strings.Replace(work, "line 20\n", "", 1)
	r.Write(map[string]string{"f.txt": work})
	s := New(t, Options{WorkDir: r.Dir})
	s.WaitGit()
	PluginOf[*editor.GitSigns](s, "gitsigns").Now = func() time.Time { return r.When.Add(3 * 24 * time.Hour) }
	s.Run("editor.open", registry.Args{"path": filepath.Join(r.Dir, "f.txt")})
	s.SettleSigns()
	return s, r
}

// SettleSigns frames until the gutter's and blame's work off the loop is done.
func (s *Scene) SettleSigns() {
	for range 3 {
		s.Frame()
		s.WaitGit()
		PluginOf[*editor.GitSigns](s, "gitsigns").Wait()
		s.RunQueued()
	}
	s.Frame()
}

// CursorTo puts the editor's cursor on a 1-based line, and lets the gutter catch up.
func (s *Scene) CursorTo(line int) {
	s.Editor().SetCursor(text.Pos{Line: line - 1})
	s.SettleSigns()
}

// SearchScene has a few Go files, one marked generated by .gitattributes, in a work dir it answers.
func SearchScene(t *testing.T) (*Scene, string) {
	dir := t.TempDir()
	rig.WriteFiles(t, dir, map[string]string{
		".gitattributes":            "gen/** linguist-generated\n",
		"internal/pricing/round.go": "package pricing\n\nfunc Round(v int) int { return v * 100 }\n\nfunc RoundMinor(v int) int { return Round(v) / 100 }\n",
		"internal/pricing/tiers.go": "package pricing\n\nfunc tier() int { return Round(3) }\n",
		"gen/api.go":                "package gen\n\nfunc Round() {}\n",
	})
	return New(t, Options{WorkDir: dir}), dir
}

// ReposScene is the Repos page on a repo with a merged branch and a tag, beside a sibling discovery found.
func ReposScene(t *testing.T) *Scene {
	t.Helper()
	lw := rig.NewHost(t)
	t.Setenv("GIT_COMMITTER_NAME", "x")
	t.Setenv("GIT_COMMITTER_EMAIL", "x@x")
	rig.Git(t, lw.Repo, "branch", "liam/eng-2190-usage-cache")
	rig.Git(t, lw.Repo, "tag", "-a", "-m", "v0.4.2", "v0.4.2")
	rig.NewRepo(t, filepath.Join(filepath.Dir(lw.Repo), "billing"))
	s := New(t, Options{Config: Connect(lw.W)})
	rig.WaitState(t, s.Store(), "the machine", func(st core.State) bool { return !st.Machine.Sampled.IsZero() })
	if _, err := lw.W.AddRepoPath(context.Background(), lw.Repo); err != nil {
		t.Fatal(err)
	}
	s.Until("the sibling found", func() bool { return len(s.Store().State().Repos) == 2 })
	s.Run("repos.open", registry.Args{"repo": "pricing"})
	s.Until("the page read", func() bool {
		f := s.Text()
		return strings.Contains(f, "Clean up 1…") && strings.Contains(f, "latest v0.4.2") && strings.Contains(f, "last commit")
	})
	return s
}
