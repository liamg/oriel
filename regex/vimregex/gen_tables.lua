-- Generates tables.go from nvim (go generate): nvim --headless --clean -l gen_tables.lua > tables.go
local out = {}
local function w(s) out[#out + 1] = s end
local function ch(c) return vim.fn.nr2char(c) end
local function valid(c) return c < 0xD800 or c > 0xDFFF end

local function ranges(pred, lo, hi)
  local rs, start = {}, nil
  for c = lo, hi + 1 do
    local yes = c <= hi and valid(c) and pred(c)
    if yes and not start then start = c end
    if not yes and start and (c > hi or valid(c)) then
      rs[#rs + 1] = { start, c - 1 }
      start = nil
    end
  end
  return rs
end

w('// Code generated by gen_tables.lua from ' .. 'nvim v' .. tostring(vim.version()) .. '; DO NOT EDIT.')
w('')
w('package vimregex')
w('')

local k, i, f, p = vim.regex([[\k]]), vim.regex([[\i]]), vim.regex([[\f]]), vim.regex([[\p]])
w('// latin1 holds the default \\k \\i \\f \\p flags for characters below 0x100.')
w('var latin1 = [256]uint8{')
local row = {}
for c = 0, 255 do
  local s, v = ch(c), 0
  if c > 0 then
    if k:match_str(s) then v = v + 1 end
    if i:match_str(s) then v = v + 2 end
    if f:match_str(s) then v = v + 4 end
    if p:match_str(s) then v = v + 8 end
  end
  row[#row + 1] = tostring(v)
  if #row == 16 then w('\t' .. table.concat(row, ', ') .. ','); row = {} end
end
w('}')
w('')

w('// charClasses lists characters from 0x100 whose class (vim\'s charclass()) is not 2.')
w('var charClasses = []classRange{')
local start, cur = nil, nil
for c = 0x100, 0x110000 do
  local cls = nil
  if c <= 0x10FFFF and valid(c) then cls = vim.fn.charclass(ch(c)) end
  if c <= 0x10FFFF and not valid(c) then goto continue end
  if cls ~= cur then
    if cur and cur ~= 2 then w(string.format('\t{0x%x, 0x%x, %d},', start, c - 1, cur)) end
    start, cur = c, cls
  end
  ::continue::
end
w('}')
w('')

w('// unprintable lists characters from 0x100 that \\p does not match.')
w('var unprintable = []runeRange{')
for _, r in ipairs(ranges(function(c) return not p:match_str(ch(c)) end, 0x100, 0x10FFFF)) do
  w(string.format('\t{0x%x, 0x%x},', r[1], r[2]))
end
w('}')
w('')

w('// composing lists characters that join the character before them.')
w('var composing = []runeRange{')
for _, r in ipairs(ranges(function(c) return vim.fn.strchars('a' .. ch(c), 1) == 1 end, 0x80, 0x10FFFF)) do
  w(string.format('\t{0x%x, 0x%x},', r[1], r[2]))
end
w('}')
w('')

local cands = {}
for c = 0x21, 0x24F do cands[#cands + 1] = c end
for c = 0x1E00, 0x1EFF do cands[#cands + 1] = c end
local seen, classes = {}, {}
for _, c in ipairs(cands) do
  if not seen[c] and c ~= 0x5D and c ~= 0x5C then
    local re = vim.regex('[[=' .. ch(c) .. '=]]')
    local members = {}
    for _, d in ipairs(cands) do
      if re:match_str(ch(d)) then members[#members + 1] = d end
    end
    if #members > 1 then
      local s = {}
      for _, d in ipairs(members) do seen[d] = true; s[#s + 1] = ch(d) end
      classes[#classes + 1] = table.concat(s)
    end
  end
end
w('// equivalences lists the characters each [[=x=]] class matches.')
w('var equivalences = []string{')
for _, s in ipairs(classes) do w('\t' .. string.format('%q', s) .. ',') end
w('}')

io.stdout:write(table.concat(out, '\n') .. '\n')
